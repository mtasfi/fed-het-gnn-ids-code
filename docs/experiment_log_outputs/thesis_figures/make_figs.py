# ------------------------------------------------------------------ r_cm: A2 vs E1, row-normalised, 2-seed sum
cm_order = ['normal', 'scanning', 'dos', 'ddos', 'backdoor', 'injection', 'xss', 'password', 'ransomware', 'mitm']
def cm(prefix):
    tot = {}
    for s in (0, 1):
        for r in rows(f'{RUNS}/{prefix}__alpha=0.5__seed={s}__confusion_matrix.csv'):
            t = r['true\\pred']
            for c in cm_order:
                tot[(t, c)] = tot.get((t, c), 0) + int(r[c])
    out = []
    for t in cm_order:
        n = sum(tot[(t, c)] for c in cm_order)
        out.append([round(100 * tot[(t, c)] / n) for c in cm_order])
    return out
def colour(v):
    t = v / 100
    return tuple(round(255 * (1 - t) + c * t) for c in (30, 58, 138))
def panel(M):
    lines = []
    for i, row in enumerate(M):
        for j, v in enumerate(row):
            r, g, b = colour(v)
            lines.append(f'\\fill[fill={{rgb,255:red,{r};green,{g};blue,{b}}}] ({j * 0.5:.1f},{-(i + 1) * 0.5:.1f}) rectangle ++(0.5,0.5);')
            if v > 0:
                lines.append(f'\\node[font=\\tiny, text={"white" if v >= 50 else "cLine"}] at ({j * 0.5 + 0.25:.2f},{-(i + 1) * 0.5 + 0.25:.2f}) {{{v}}};')
    return '\n'.join(lines)
src = open(f'{FIG}/r_cm.tex').read()
scopes = re.split(r'(\\begin\{scope\}\[xshift=[^\]]*\]\n\\node\[[^\n]*\n)', src)
# scopes: [head, scope1_header, scope1_body, scope2_header, scope2_body...]
def body_rest(body):
    k = body.index('\\draw[white, line width=0.5pt]') if '\\draw[white, line width=0.5pt]' in body else body.index('\\fill[fill={rgb,255:red,35')
    return body[k:]
A2m, E1m = cm('A2__toniot__hashed_ngrams'), cm('E1__toniot__main')
